describe('Lógica de negócio - Registro Automático (FASE 3 - M1)', () => {
  describe('Duração com regra de meia-noite', () => {
    it('calcula duração correta quando end <= start (cruzou meia-noite)', () => {
      // 22:00 = 1320 min, 02:00 = 120 min + 1440 = 1560 min
      const startTime = '22:00';
      const endTime = '02:00';
      const [sh, sm] = startTime.split(':').map(Number);
      const [eh, em] = endTime.split(':').map(Number);
      let startMin = sh * 60 + sm;
      let endMin = eh * 60 + em;
      if (endMin <= startMin) endMin += 24 * 60;
      const duration = endMin - startMin;
      
      expect(duration).toBe(240); // 4 horas
    });

    it('calcula duração normal quando end > start', () => {
      const startTime = '19:00';
      const endTime = '21:00';
      const [sh, sm] = startTime.split(':').map(Number);
      const [eh, em] = endTime.split(':').map(Number);
      let startMin = sh * 60 + sm;
      let endMin = eh * 60 + em;
      if (endMin <= startMin) endMin += 24 * 60;
      const duration = endMin - startMin;
      
      expect(duration).toBe(120); // 2 horas
    });
  });

  describe('Regra "manual vence" - comparação de discipline', () => {
    it('ignora caixa e espaços extras', () => {
      const discipline1 = '  DIREITO CONSTITUCIONAL  ';
      const discipline2 = 'direito constitucional';
      
      const normalized1 = discipline1.trim().toLowerCase();
      const normalized2 = discipline2.trim().toLowerCase();
      
      expect(normalized1).toBe(normalized2);
    });

    it('diferentes disciplines não batem', () => {
      const discipline1 = 'Português';
      const discipline2 = 'Direito Constitucional';
      
      const normalized1 = discipline1.trim().toLowerCase();
      const normalized2 = discipline2.trim().toLowerCase();
      
      expect(normalized1).not.toBe(normalized2);
    });
  });

  describe('Activity types que não geram registro', () => {
    it('break não gera registro', () => {
      const activityType: string = 'break';
      expect(activityType === 'break' || activityType === 'other').toBe(true);
    });

    it('other não gera registro', () => {
      const activityType: string = 'other';
      expect(activityType === 'break' || activityType === 'other').toBe(true);
    });

    it('theory gera registro', () => {
      const activityType: string = 'theory';
      expect(activityType === 'break' || activityType === 'other').toBe(false);
    });

    it('questions gera registro', () => {
      const activityType: string = 'questions';
      expect(activityType === 'break' || activityType === 'other').toBe(false);
    });
  });
});

describe('Lógica de negócio - Estatísticas (FASE 4 - M2)', () => {
  describe('Cálculo de adherence', () => {
    it('adherence = 0 quando plannedMinutes = 0', () => {
      const plannedMinutes = 0;
      const effectiveMinutes = 100;
      const adherence = plannedMinutes > 0 ? effectiveMinutes / plannedMinutes : 0;
      
      expect(adherence).toBe(0);
    });

    it('adherence > 100% possível (sem cap)', () => {
      const plannedMinutes = 120;
      const effectiveMinutes = 180;
      const adherence = effectiveMinutes / plannedMinutes;
      
      expect(adherence).toBe(1.5); // 150%
    });

    it('adherence = 100% quando igual', () => {
      const plannedMinutes = 120;
      const effectiveMinutes = 120;
      const adherence = effectiveMinutes / plannedMinutes;
      
      expect(adherence).toBe(1);
    });
  });

  describe('daysWithActivity - dias únicos', () => {
    it('conta dias únicos com registro efetivo', () => {
      const records: Array<{ date: string; duration: number; isDeleted?: boolean }> = [
        { date: '2026-11-16', duration: 60 },
        { date: '2026-11-16', duration: 60 }, // Mesmo dia
        { date: '2026-11-17', duration: 60 },
      ];
      
      const daysSet = new Set<string>();
      for (const r of records) {
        if (!r.isDeleted) daysSet.add(r.date);
      }
      
      expect(daysSet.size).toBe(2); // 16 e 17
    });

    it('ignora registros isDeleted=true', () => {
      const records: Array<{ date: string; duration: number; isDeleted?: boolean }> = [
        { date: '2026-11-16', duration: 60, isDeleted: false },
        { date: '2026-11-17', duration: 60, isDeleted: true },
      ];
      
      const daysSet = new Set<string>();
      for (const r of records) {
        if (!r.isDeleted) daysSet.add(r.date);
      }
      
      expect(daysSet.size).toBe(1); // Apenas 16
    });
  });

  describe('Planejado vs Efetivo', () => {
    it('plannedMinutes soma durações de ocorrências não suprimidas', () => {
      const occ1 = { start_time: '19:00', end_time: '21:00' }; // 120 min
      const occ2 = { start_time: '08:00', end_time: '10:00' }; // 120 min
      
      let total = 0;
      for (const occ of [occ1, occ2]) {
        const [sh, sm] = occ.start_time.split(':').map(Number);
        const [eh, em] = occ.end_time.split(':').map(Number);
        let startMin = sh * 60 + sm;
        let endMin = eh * 60 + em;
        if (endMin <= startMin) endMin += 24 * 60;
        total += endMin - startMin;
      }
      
      expect(total).toBe(240);
    });

    it('missed conta como planejado', () => {
      // A lógica do getStudyStatistics não filtra por status para plannedMinutes
      // missed também foi planejado
      const statuses = ['pending', 'done', 'missed'];
      for (const status of statuses) {
        // Todos entram no plannedMinutes
        expect(['pending', 'done', 'missed']).toContain(status);
      }
    });

    it('done/missed não são suprimidos por pausa (histórico preservado)', () => {
      const eventDone = { status: 'done', isOverride: false, isDeleted: false };
      const eventMissed = { status: 'missed', isOverride: false, isDeleted: false };
      const eventPending = { status: 'pending', isOverride: false, isDeleted: false };
      
      // done e missed preservam histórico
      // pending pode ser suprimido
      expect(eventDone.status === 'done' || eventDone.status === 'missed').toBe(true);
      expect(eventMissed.status === 'done' || eventMissed.status === 'missed').toBe(true);
      expect(eventPending.status === 'done' || eventPending.status === 'missed').toBe(false);
    });
  });
});

