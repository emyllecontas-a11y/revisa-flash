  ADD COLUMN IF NOT EXISTS "occurrenceSourceType" text CHECK ("occurrenceSourceType" IN ('block','extra')),
  ADD COLUMN IF NOT EXISTS "occurrenceSourceId" uuid,
  ADD COLUMN IF NOT EXISTS "occurrenceDate" date,
  ADD COLUMN IF NOT EXISTS "autoGenerated" boolean DEFAULT false;

-- Índice para consultas de idempotência (chave composta de negócio)
CREATE INDEX IF NOT EXISTS idx_study_records_auto_link
  ON public.study_records (user_id, "occurrenceSourceType", "occurrenceSourceId", "occurrenceDate")
  WHERE "autoGenerated" = true AND "isDeleted" = false;

-- 3. Atualizar RPC salvar_study_records_batch para incluir as 4 colunas
-- A RPC recebe payload com nomes em camelCase (do RxDB) e mapeia 1:1 para as colunas (sem tradução)

CREATE OR REPLACE FUNCTION public.salvar_study_records_batch(p_records jsonb)
 RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public'
AS $function$
declare
  v_record jsonb; v_count integer := 0; v_skipped integer := 0; v_rows integer;
  v_uid text := public.get_user_id();
begin
  if v_uid is null then raise exception 'Não autenticado'; end if;
  for v_record in select * from jsonb_array_elements(p_records) loop
    if (v_record->>'user_id') is distinct from v_uid then
      v_skipped := v_skipped + 1; continue;
    end if;
    insert into study_records (
      id, user_id, date, type, discipline, topic, duration, material,
      "questionsCount", "correctCount", "wrongCount", source, observations,
      "createdAt", updated_at, "isDeleted",
      "occurrenceSourceType", "occurrenceSourceId", "occurrenceDate", "autoGenerated"
    ) values (
      v_record->>'id', v_uid, (v_record->>'date')::date, v_record->>'type',
      v_record->>'discipline', v_record->>'topic', (v_record->>'duration')::integer,
      v_record->>'material', (v_record->>'questionsCount')::integer,
      (v_record->>'correctCount')::integer, (v_record->>'wrongCount')::integer,
      v_record->>'source', v_record->>'observations',
      (v_record->>'createdAt')::timestamptz, (v_record->>'updated_at')::timestamptz,
      coalesce((v_record->>'isDeleted')::boolean, false),
      v_record->>'occurrenceSourceType', (v_record->>'occurrenceSourceId')::uuid,
      (v_record->>'occurrenceDate')::date, coalesce((v_record->>'autoGenerated')::boolean, false)
    )
    on conflict (id) do update set
      date = excluded.date, type = excluded.type, discipline = excluded.discipline,
      topic = excluded.topic, duration = excluded.duration, material = excluded.material,
      "questionsCount" = excluded."questionsCount", "correctCount" = excluded."correctCount",
      "wrongCount" = excluded."wrongCount", source = excluded.source,
      observations = excluded.observations, "createdAt" = excluded."createdAt",
      updated_at = excluded.updated_at, "isDeleted" = excluded."isDeleted",
      "occurrenceSourceType" = excluded."occurrenceSourceType",
      "occurrenceSourceId" = excluded."occurrenceSourceId",
      "occurrenceDate" = excluded."occurrenceDate",
      "autoGenerated" = excluded."autoGenerated"
    where study_records.user_id = v_uid;
    get diagnostics v_rows = row_count;
    v_count := v_count + v_rows;
  end loop;
  return jsonb_build_object('success', true, 'count', v_count, 'skipped', v_skipped);
end;
$function$;

-- 4. Permissões
REVOKE EXECUTE ON FUNCTION public.salvar_study_records_batch(jsonb) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.salvar_study_records_batch(jsonb) TO authenticated;

